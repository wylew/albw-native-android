#!/usr/bin/env python3
"""Tripwire stubs for every symbol still unresolved after linking the game.

  python3 tools/gen_stubs.py build/albw_game.o native-object.o ... > build/stubs.c

Each unresolved function gets a definition that aborts with its name and caller, so running the
game reports exactly which missing piece is needed next. Unresolved data gets a zeroed 4 KiB
block (also listed in the output). Generated into build/: the list changes as work lands.
"""
import os
import re
import subprocess
import sys


def syms(obj, *flags):
    out = subprocess.run(["llvm-nm", *flags, "--format=just-symbols", obj], capture_output=True, text=True)
    return set(out.stdout.split())


# ALBW_ARCH=x86_64 (tools/link64.sh, build_decomp.py --arch x86_64): the 64-bit libraries
# Library folders differ by distribution: Arch /usr/lib32, Debian/Ubuntu /usr/lib/i386-linux-gnu (and
# /lib/...), Fedora/openSUSE /usr/lib; build.sh's own SDL3 in build/deps. A library not found here had
# its functions stubbed, and the stubs shadowed the real ones (Ubuntu: "stub SDL_Init called").
_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_ANDROID = os.environ.get("ALBW_ARCH") == "arm32"   # tools/link_android.sh
if _ANDROID:
    # ALBW_NDK_TOOLCHAIN: .../toolchains/llvm/prebuilt/linux-x86_64 (set by link_android.sh)
    _TC = os.environ["ALBW_NDK_TOOLCHAIN"]
    _API = os.environ.get("ALBW_ANDROID_API", "24")
    _DIRS = [os.path.join(_TC, "sysroot", "usr", "lib", "arm-linux-androideabi", _API),
             os.path.join(_ROOT, "build", "deps", "sdl3-android-armv7", "lib")]
elif os.environ.get("ALBW_ARCH") == "x86_64":
    _DIRS = ["/usr/lib", "/usr/lib/x86_64-linux-gnu", "/lib/x86_64-linux-gnu", "/usr/lib64", "/lib64"]
else:
    _DIRS = [os.path.join(_ROOT, "build", "deps", "sdl3-i686", "lib"), "/usr/lib32",
             "/usr/lib/i386-linux-gnu", "/lib/i386-linux-gnu"]
    if os.path.isdir("/usr/lib64") and not os.path.isdir("/usr/lib32"):
        _DIRS += ["/usr/lib", "/lib"]   # Fedora / openSUSE: 32-bit in /usr/lib (64-bit on Arch)


def _find(name):
    for d in _DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    sys.exit("gen_stubs: %s not found in %s (32-bit library missing?)" % (name, ", ".join(_DIRS)))


if _ANDROID:
    import glob
    SYSTEM_LIBS = [_find(n) for n in ("libc.so", "libm.so", "libdl.so", "liblog.so", "libandroid.so",
                                      "libSDL3.so", "libz.so")]
    SYSTEM_LIBS += [_find("crtbegin_so.o")]   # atexit, __dso_handle (linked into every .so)
    # compiler runtime (static): __aeabi_*, __udivdi3, _Unwind_* ...
    SYSTEM_LIBS += glob.glob(os.path.join(_TC, "lib", "clang", "*", "lib", "linux", "libclang_rt.builtins-arm-android.a"))
    SYSTEM_LIBS += glob.glob(os.path.join(_TC, "lib", "clang", "*", "lib", "linux", "arm", "libunwind.a"))
else:
    SYSTEM_LIBS = [_find(n) for n in ("libc.so.6", "libm.so.6", "libSDL3.so.0", "libz.so.1")]  # libz: save states


def system_symbols():
    """Names the system libraries provide: never stub those (a stub would shadow libc)."""
    out = set()
    for lib in SYSTEM_LIBS:
        dyn = [] if lib.endswith((".a", ".o")) else ["-D"]
        r = subprocess.run(["llvm-nm", *dyn, "--defined-only", "--format=just-symbols", lib], capture_output=True, text=True)
        out |= {x.split("@")[0] for x in r.stdout.split()}
    return out


def main():
    # --defs=LIB: only contributes definitions (a prebuilt library linked as well, e.g. the Qt
    # frontend; its own undefined references are resolved by its libraries, never stubbed)
    objs = [x for x in sys.argv[1:] if not x.startswith("--defs=")]
    system = system_symbols()
    defined, undefined = set(), set()
    for x in sys.argv[1:]:
        if x.startswith("--defs="):
            defined |= syms(x[len("--defs="):], "--defined-only", "--extern-only")
    for o in objs:
        defined |= syms(o, "--defined-only", "--extern-only")  # exported definitions only
        undefined |= syms(o, "-u")
    # versioned references (name@GLIBC_x, native/runtime/glibc_compat.c) are bound by the libraries
    missing = sorted(x for x in undefined - defined if "@" not in x)
    libc_like = re.compile(r"^(mem|str|__aeabi_|__cxa_|_Unwind|__gxx|__stack_chk|__asan_|__ubsan_|__sanitizer_|__lsan_|_GLOBAL_OFFSET_TABLE_$|__dso_handle$)")
    out = ['/* generated by tools/gen_stubs.py: tripwires for unresolved symbols */',
           '#include "../native/runtime/runtime.h"',
           '/* data blocks in their own section: save-state conversion never maps a word into them (runtime/ss_convert.c) */',
           '#if defined(_WIN32)', '#define TRIPWIRE_DATA', '#else', '#define TRIPWIRE_DATA __attribute__((section(".tripwire_data")))', '#endif', ""]
    nfun = ndat = 0
    for i, s in enumerate(missing):
        if libc_like.match(s) or s in system:
            continue  # provided by the C library / compiler runtime at final link
        m = re.match(r"^DAT_0000([0-9a-f]{4})$", s)
        if m:
            # Ghidra's name for a small CONSTANT below the image (`&DAT_00000040` = 0x40, compared
            # with a byte in the text provider 00167E44): every use takes the address, so the
            # symbol is the number itself (absolute), not a data block. As a 4 KiB stub the
            # comparison never matched and the dialogue box got a 16-character buffer (BOOT_LOG 107 [3d])
            out.append('__asm__(".globl %s\\n.set %s, 0x%s");' % (s, s, m.group(1)))
            ndat += 1
            continue
        if s.startswith(("data_", "DAT_", "_ZTV", "_ZTI", "_ZTS")) or re.match(r"^[a-z]*Ram[0-9a-f]{8}$", s):
            out.append('__attribute__((aligned(16), visibility("hidden"))) TRIPWIRE_DATA unsigned char stub_data_%d[4096] __asm__("%s");' % (i, s))
            ndat += 1
            continue
        # hidden: the binary is linked with -rdynamic, and an exported stub named like a C++
        # runtime symbol (_ZdlPv, _ZTVN10__cxxabiv1...) would interpose libstdc++ for host
        # libraries (GL/EGL drivers) loaded at run time
        out.append('void stub_%d(void) __asm__("%s") __attribute__((visibility("hidden")));' % (i, s))
        out.append('void stub_%d(void) { runtime_fatal("stub %s called from %%p", __builtin_return_address(0)); }'
                   % (i, s.replace('"', '')))
        nfun += 1
    print("\n".join(out))
    print("tripwire stubs: %d functions, %d data blocks" % (nfun, ndat), file=sys.stderr)


if __name__ == "__main__":
    main()
